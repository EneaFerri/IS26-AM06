package it.polimi.ingsw.model.enums;

/**
 * Identifies a specific invention token that can be owned by a player.
 *
 * <p>Invention tokens are collected through Inventor character cards and
 * contribute to the Inventor's prestige scoring at end of game.</p>
 */
public enum InventionType {

    /** Boat invention token. */
    BOAT,

    /** Arrow invention token. */
    ARROW,

    /** Hook invention token. */
    HOOK,

    /** Necklace invention token. */
    NECKLACE,

    /** Cup invention token. */
    CUP,

    /** Rope invention token. */
    ROPE,

    /** Voodoo invention token. */
    VOODOO,

    /** Flute invention token. */
    FLUTE,

    /** Leather invention token. */
    LEATHER,

    /** Bread invention token. */
    BREAD
}
